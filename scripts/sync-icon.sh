#!/usr/bin/env bash
# Sync the plugin icon from wavekat/wavekat-brand (the source of truth).
#
# The Claude directory needs a square PNG (512-2048 px), but the brand repo
# ships SVG, so this fetches the brand SVG, renders it to a 1024 px PNG and
# records which brand commit it came from. Don't edit icon.png by hand;
# change the SVG in wavekat-brand and run this (or let CI do it).
#
# Needs: curl, rsvg-convert (brew install librsvg / apt install librsvg2-bin).
set -euo pipefail

BRAND_REPO="wavekat/wavekat-brand"
BRAND_REF="${BRAND_REF:-main}"
ICON_SVG="assets/logos/wavekat-icon-light.svg"   # black tile, readable on light and dark pages
SIZE=1024

root="$(cd "$(dirname "$0")/.." && pwd)"
out_dir="$root/plugins/wavekat/.claude-plugin"
png="$out_dir/icon.png"
stamp="$root/scripts/icon.lock"

auth=()
[ -n "${GH_TOKEN:-}" ] && auth=(-H "Authorization: Bearer $GH_TOKEN")
sha=$(curl -fsSL ${auth[@]+"${auth[@]}"} -H "Accept: application/vnd.github.sha" \
  "https://api.github.com/repos/$BRAND_REPO/commits/$BRAND_REF")
svg_url="https://raw.githubusercontent.com/$BRAND_REPO/$sha/$ICON_SVG"

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
curl -fsSL "$svg_url" -o "$tmp/icon.svg"
svg_hash=$(sha256sum "$tmp/icon.svg" 2>/dev/null | awk '{print $1}' \
  || shasum -a 256 "$tmp/icon.svg" | awk '{print $1}')

# Re-render only when the SVG itself changed, so different rsvg versions
# don't churn the PNG.
if [ -f "$png" ] && [ -f "$stamp" ] && grep -q "svg_sha256: $svg_hash" "$stamp"; then
  echo "icon up to date (brand $ICON_SVG unchanged)"
  exit 0
fi

rsvg-convert -w "$SIZE" -h "$SIZE" "$tmp/icon.svg" -o "$png"
cat > "$stamp" <<STAMP
# Generated by scripts/sync-icon.sh. Do not edit.
source: https://github.com/$BRAND_REPO/blob/$sha/$ICON_SVG
svg_sha256: $svg_hash
size: ${SIZE}x${SIZE}
STAMP
echo "icon synced from $BRAND_REPO@${sha:0:7}"
